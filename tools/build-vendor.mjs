// Bundles the host half's third-party dependencies into vendor/deps.js so the
// installed plugin runs with zero npm dependencies.
import { build } from 'esbuild'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const PLUGIN = dirname(dirname(fileURLToPath(import.meta.url)))
const ENTRY = join(PLUGIN, 'tools', 'vendor-entry.mjs')
const OUTPUT = join(PLUGIN, 'vendor', 'deps.js')

const result = await build({
  absWorkingDir: PLUGIN,
  entryPoints: [ENTRY],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node24',
  charset: 'utf8',
  write: false,
  logLevel: 'silent',
  banner: { js: '// Generated by tools/build-vendor.mjs. Do not edit by hand.' },
})
if (result.warnings.length > 0) throw new Error(`esbuild warnings:\n${result.warnings.map(warning => warning.text).join('\n')}`)
const text = result.outputFiles[0].text
const { writeFileSync, mkdirSync } = await import('node:fs')
mkdirSync(dirname(OUTPUT), { recursive: true })
writeFileSync(OUTPUT, text)
console.log(`vendor/deps.js written (${text.length} bytes)`)
