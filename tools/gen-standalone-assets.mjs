// One-shot generator: turns Zotero's published global schema (schema.json from
// zotero/zotero-schema) and the userdata.sql DDL (reference/zotero) into two
// bundled assets used to create standalone libraries:
//   src/host/schema-data.js  - item types, fields, creator types, CSL maps
//   src/host/userdata-sql.js - the CREATE TABLE statements (dbDebug stripped)
// Run: node tools/gen-standalone-assets.mjs <schema.json> <userdata.sql>
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const schemaPath = process.argv[2] ?? path.join(root, '.tmp-schema.json')
const sqlPath = process.argv[3] ?? path.join(root, 'reference', 'zotero', 'resource', 'schema', 'userdata.sql')

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'))
const sql = fs.readFileSync(sqlPath, 'utf8')

// --- compact global schema --------------------------------------------------
const itemTypes = schema.itemTypes.map((type) => {
  const fields = []
  const fieldBases = {}
  for (const entry of type.fields) {
    if (typeof entry === 'string') fields.push(entry)
    else {
      fields.push(entry.field)
      if (entry.baseField) fieldBases[entry.field] = entry.baseField
    }
  }
  return {
    itemType: type.itemType,
    fields,
    fieldBases,
    creatorTypes: type.creatorTypes.map(creator => (creator.primary ? { creatorType: creator.creatorType, primary: true } : { creatorType: creator.creatorType })),
  }
})
const compact = {
  version: schema.version,
  itemTypes,
  csl: { types: schema.csl.types, fields: schema.csl.fields, names: schema.csl.names },
}
const schemaJs = `// Generated by tools/gen-standalone-assets.mjs from Zotero's published global
// schema (zotero/zotero-schema schema.json v${schema.version}). Item types,
// fields, creator types, and the CSL maps used for citation export.
export const GLOBAL_SCHEMA = ${JSON.stringify(compact)}
`
fs.writeFileSync(path.join(root, 'src', 'host', 'schema-data.js'), schemaJs)

// --- userdata DDL ------------------------------------------------------------
const versionMatch = /^--\s*(\d+)/.exec(sql)
if (!versionMatch) throw new Error('userdata.sql: no leading version comment')
const version = Number(versionMatch[1])
const cleaned = sql
  .replace(/CREATE TABLE dbDebug[12][\s\S]*?\);/g, '')
  .replace(/^--.*$/gm, '')
  .trim()
const sqlJs = `// Generated by tools/gen-standalone-assets.mjs from Zotero's userdata.sql
// (schema version ${version}), comments and debug tables stripped. Used to
// create a fresh standalone library database.
export const USERDATA_SCHEMA_VERSION = ${version}
export const USERDATA_SQL = ${JSON.stringify(cleaned)}
`
fs.writeFileSync(path.join(root, 'src', 'host', 'userdata-sql.js'), sqlJs)

console.log(`schema-data.js: ${itemTypes.length} item types, csl maps`)
console.log(`userdata-sql.js: schema ${version}, ${Math.round(cleaned.length / 1024)} KB DDL`)
