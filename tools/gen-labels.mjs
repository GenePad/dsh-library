// One-shot generator: zh-CN labels for the item pane, extracted from Zotero's
// locale files (chrome/locale/zh-CN/zotero/zotero.properties + schema.ftl in
// the vendored reference/zotero tree). Output is committed as source:
//   src/client/labels.js - item types, all fields, creator types
// Run: node tools/gen-labels.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const propertiesPath = path.join(root, 'reference', 'zotero', 'chrome', 'locale', 'zh-CN', 'zotero', 'zotero.properties')
const ftlPath = path.join(root, 'reference', 'zotero', 'chrome', 'locale', 'zh-CN', 'zotero', 'schema.ftl')

// .properties values may carry legacy \\uXXXX escapes (latin-1 authored files).
function decodePropertiesValue(value) {
  return String(value).replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCharCode(Number.parseInt(hex, 16)))
}

function parseProperties(text) {
  const map = new Map()
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (line === '' || line.startsWith('#') || line.startsWith('!')) continue
    const eq = line.indexOf('=')
    if (eq === -1) continue
    const key = line.slice(0, eq).trim()
    map.set(key, decodePropertiesValue(line.slice(eq + 1).trim()))
  }
  return map
}

// Fluent line: `itemFields-partNumber = 分册号`
function parseFtlSimple(text, prefix) {
  const map = new Map()
  const pattern = new RegExp(`^${prefix}-([A-Za-z0-9]+)\\s*=\\s*(.+)$`, 'gm')
  let match
  while ((match = pattern.exec(text)) !== null) map.set(match[1], match[2].trim())
  return map
}

const properties = parseProperties(fs.readFileSync(propertiesPath, 'utf8'))
const ftlFields = parseFtlSimple(fs.readFileSync(ftlPath, 'utf8'), 'itemFields')
const ftlCreators = parseFtlSimple(fs.readFileSync(ftlPath, 'utf8'), 'creatorTypes')

const itemTypes = {}
const fields = {}
const creatorTypes = {}
for (const [key, value] of properties) {
  if (key.startsWith('itemTypes.')) itemTypes[key.slice('itemTypes.'.length)] = value
  else if (key.startsWith('itemFields.')) fields[key.slice('itemFields.'.length)] = value
  else if (key.startsWith('creatorTypes.')) creatorTypes[key.slice('creatorTypes.'.length)] = value
}
// Newer schema fields/types only exist in schema.ftl.
for (const [key, value] of ftlFields) if (fields[key] === undefined) fields[key] = value
for (const [key, value] of ftlCreators) if (creatorTypes[key] === undefined) creatorTypes[key] = value

// Labels Zotero builds from strings rather than the properties file.
const extras = {
  __placeholders: {
    firstName: properties.get('pane.item.defaultFirstName') ?? '名',
    lastName: properties.get('pane.item.defaultLastName') ?? '姓',
    fullName: properties.get('pane.item.defaultFullName') ?? '姓名',
  },
  dateAdded: properties.get('pane.item.dateAdded.dateAdded') ?? '添加日期',
  dateModified: properties.get('pane.item.dateModified.dateModified') ?? '修改日期',
}

const js = `// Generated by tools/gen-labels.mjs from Zotero's zh-CN locale
// (reference/zotero chrome/locale/zh-CN/zotero). Item type, field and creator
// type labels for the item pane; committed as source, regenerate only when the
// vendored Zotero tree updates.
export const ITEM_TYPE_LABELS = ${JSON.stringify(itemTypes, null, 2)}

export const FIELD_LABELS = ${JSON.stringify(fields, null, 2)}

export const CREATOR_TYPE_LABELS = ${JSON.stringify(creatorTypes, null, 2)}

// Strings Zotero keeps in code: creator placeholders and the read-only
// dateAdded/dateModified rows at the bottom of the info section.
export const PANE_LABELS = ${JSON.stringify(extras, null, 2)}
`

fs.writeFileSync(path.join(root, 'src', 'client', 'labels.js'), js)
console.log(`labels.js: ${Object.keys(itemTypes).length} item types, ${Object.keys(fields).length} fields, ${Object.keys(creatorTypes).length} creator types`)
